import { chromium } from "playwright";
const b = await chromium.launch({ args: ["--use-gl=swiftshader", "--enable-unsafe-swiftshader"] });
const p = await (await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true })).newPage();
await p.goto(`http://127.0.0.1:5173/v/${process.argv[2]}`);
await p.waitForFunction(() => window.__einwurfMap?.getLayer("buildings-fill"), null, { timeout: 30000 });
await p.evaluate(() => window.__einwurfMap.jumpTo({ zoom: 15.2 }));
await p.waitForTimeout(15000);
console.log(await p.evaluate(() => { const m = window.__einwurfMap; return { center: m.getCenter(), n: m.queryRenderedFeatures({ layers: ["buildings-fill"] }).length, src: m.getSource("buildings")._data?.features?.length ?? m.getSource("buildings").serialize().data.features?.length }; }));
await p.screenshot({ path: process.argv[3] });
await b.close();
